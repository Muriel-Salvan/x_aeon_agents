describe XAeonAgents::Agents::ReadmeGeneratorAgent do
  describe 'grouping headers generated by the section agents' do
    before do
      stub_doctoc
      # Stub the section agents to wrap their content in a single grouping header, as the AI
      # agents sometimes do when they generate a whole section.
      stub_agent_run(
        stub_handler: lambda { |agent, **_kwargs|
          agent.track_message(message: 'mocked AI response', author: 'assistant')
          case agent
          when XAeonAgents::Agents::Readme::AboutAnalyzerAgent
            { name: 'Test Project', description: 'A test project', about: 'Generated content for about' }
          when XAeonAgents::Agents::Readme::QuickStartAgent
            {
              quick_start: <<~EO_CONTENT
                # Quick start guide

                Install the gem and run it.
              EO_CONTENT
            }
          else
            {}
          end
        }
      )
    end

    # Only generate the sections that are stubbed in this spec
    def run_kwargs
      {
        gen_requirements: false,
        gen_features: false,
        gen_public_api: false,
        gen_documentation: false,
        gen_how_it_works: false,
        gen_development: false,
        gen_contributing: false,
        gen_license: false
      }
    end

    it 'removes the single grouping header wrapping the content generated for a section' do
      run_readme_generator(run_kwargs:)
      expect(readme_content).to include(<<~EO_SECTION)
        ## Quick start

        Install the gem and run it.
      EO_SECTION
      expect(readme_content).not_to include('Quick start guide')
    end

    it 'generates a README when the existing one does not have any heading' do
      run_readme_generator(run_kwargs:, existing_content: "Old readme content, without any heading.\n")
      expect(readme_content).to include(<<~EO_SECTION)
        ## Quick start

        Install the gem and run it.
      EO_SECTION
    end
  end
end
